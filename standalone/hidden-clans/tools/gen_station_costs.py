#!/usr/bin/env python3
"""Read what each workshop recipe uses from the original station code.

Writes game/Code/Remastered/StationCosts.dm: "station>recipe" -> what it uses
and which skill it trains. Display only; the station code itself decides.
Run again whenever CraftingStations.dm changes.
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / 'game/Code/Items/CraftingStations.dm'
OUT = ROOT / 'game/Code/Remastered/StationCosts.dm'
STATIONS = {'Forge': 'forge', 'Smelters': 'smelter', 'Carpentry': 'carpentry', 'BoneCraft': 'bone', 'LeatherWorks': 'leather',
            'Masonary': 'masonry', 'GemCutter': 'gem', 'Kitchen': 'kitchen', 'PotionStation': 'potion', 'PoisonStation': 'poison'}
SKILLS = {'MetalCraftingSkill': 'Smithing', 'WoodCraftingSkill': 'Woodwork', 'BoneCraftingSkill': 'Bone craft', 'LeatherCraftingSkill': 'Leatherwork',
          'StoneCraftingSkill': 'Masonry', 'GemCuttingSkill': 'Gem cutting', 'CookingSkill': 'Cooking', 'PotionSkill': 'Alchemy', 'PoisonSkill': 'Poisons',
          'SmeltingSkill': 'Smelting', 'MasonarySkill': 'Masonry', 'JewelCraftingSkill': 'Jewel craft'}


def nice(path):
    name = path.split('/')[-1]
    name = re.sub(r'(?<=[a-z])(?=[A-Z])', ' ', name).replace('_', ' ')
    return name.lower()


def main():
    lines = SRC.read_text(encoding='latin-1').splitlines()
    station = None
    costs = {}
    current = None
    for line in lines:
        m = re.match(r'^\t\t([A-Za-z]+)\s*$', line)
        if m and m.group(1) in STATIONS:
            station = STATIONS[m.group(1)]
            current = None
            continue
        if m and m.group(1) not in STATIONS and station and not line.startswith('\t\t\t'):
            station = None
        if not station:
            continue
        r = re.search(r'Result\d*\s*==\s*"([^"]+)"', line)
        if r:
            current = (station, r.group(1))
            costs.setdefault(current, {'items': [], 'skill': None})
            continue
        if not current:
            continue
        for item in re.findall(r'for\s*\(\s*var/obj/Items/([\w/]+)/\w+\s+in\s+M\s*\)', line):
            n = nice(item)
            if n not in costs[current]['items']:
                costs[current]['items'].append(n)
        s = re.search(r'M\.(\w+Skill)\s*\+=', line)
        if s and not costs[current]['skill']:
            costs[current]['skill'] = SKILLS.get(s.group(1), re.sub(r'Skill$', '', s.group(1)))
    out = ['// Generated by tools/gen_station_costs.py from Code/Items/CraftingStations.dm. Do not edit.',
           '// "station>recipe" -> list(uses, skill). Display only.',
           'var/list/remaster_station_costs = list(']
    rows = []
    for (st, recipe), c in sorted(costs.items()):
        if not c['items'] and not c['skill']:
            continue
        uses = ', '.join(c['items'][:4]).replace('"', "'")
        rows.append(f'\t"{st}>{recipe}" = list("{uses}", "{c["skill"] or ""}")')
    out.append(',\n'.join(rows))
    out.append(')')
    OUT.write_text('\n'.join(out) + '\n')
    print(f'{len(rows)} recipes with costs -> {OUT.relative_to(ROOT)}')


if __name__ == '__main__':
    main()
