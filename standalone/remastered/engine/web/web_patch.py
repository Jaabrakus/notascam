def _verbatim(text):
    return '@"' + text.replace('"', '""') + '"'


def generate(here, src):
    here = Path(here)
    read = lambda name: (here/name).read_text(encoding='utf-8')
    (Path(src)/'RmWebShim.cs').write_text(
        '// Generated by engine/web/web_patch.py from dmweb-head.js, dmweb.js and the lobby, joining, ended, signin, guest form and refused pages.\n'
        'namespace OpenDreamRuntime;\n\n'
        'internal static class RmWebShim {\n'
        f'    private const string HeadScript = {_verbatim(read("dmweb-head.js"))};\n'
        f'    public const string Tail = {_verbatim(read("dmweb.js"))};\n'
        f'    public const string Lobby = {_verbatim(read("lobby.html"))};\n'
        f'    public const string Ended = {_verbatim(read("ended.html"))};\n'
        f'    public const string SignIn = {_verbatim(read("signin.html"))};\n'
        f'    public const string Refused = {_verbatim(read("refused.html"))};\n'
        f'    public const string GuestForm = {_verbatim(read("guestform.html"))};\n'
        f'    private const string JoiningPage = {_verbatim(read("joining.html"))};\n\n'
        '    public static string Head(int protocol, int pageVersion) =>\n'
        '        HeadScript.Replace("__V__", protocol.ToString()).Replace("__PV__", pageVersion.ToString());\n\n'
        '    public static string Joining(int protocol) => JoiningPage.Replace("__HEAD__", Head(protocol, 0)).Replace("__TAIL__", Tail);\n'
        '}\n', encoding='utf-8')
