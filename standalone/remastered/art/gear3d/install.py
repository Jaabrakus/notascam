# Puts the 3D gear and the unit animations into the game (python3 install.py PIX [RIG]): the page's scripts
# (gear3d, ragdoll, skills, deaths, work, magicfx, bosses) as one file, game/Interface/gear3d.js, which View3D's page puts in
# at its rm-gear3d marker (Gear3D.dm); the files the page fetches, in game/Interface/gear3d/ (sent once to each player,
# Gear3D.dm); and game/Code/Remastered/Gear3DData.dm, what the server needs to know about them (which pieces have a 3D
# look, which race sheets have anchors, the files to send). PIX: the palette pictures (smoothgear.py --index) with
# gear3d-pix.json and the magic effect frames (fxsheet.py); RIG: the races' part maps (parts.py). Edit the sources here,
# not the copies in game/.
import json, os, shutil, sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
GAME = Path(os.environ.get('G3GAME_DIR') or HERE.parents[1]/'game')   # G3GAME_DIR: a clone of game/ to test first
SCRIPTS = ('gear3d.js', 'ragdoll.js', 'skills.js', 'deaths.js', 'work.js', 'magicfx.js', 'bosses.js', 'game.js')


def main(pix, rig=None):
    pix = Path(pix)
    out = GAME/'Interface'/'gear3d'
    if out.exists():
        shutil.rmtree(out)
    out.mkdir(parents=True)
    files = []
    def put(src, name=None):
        name = name or src.name
        shutil.copy2(src, out/name)
        files.append(name)
    put(HERE/'gear3d.json')
    put(HERE/'anchors.json', 'gear3d-anchors.json')
    put(HERE/'g3sack.png')
    for f in sorted(pix.iterdir()):
        if f.name == 'gear3d-pix.json' or f.name == 'g3fx.json' or (f.suffix == '.png' and f.name.startswith(('g3p-', 'g3fx-'))):
            put(f)
    meta = json.load(open(pix/'gear3d-pix.json'))
    assert meta.get('index'), 'PIX must be the palette pictures (smoothgear.py --index)'
    if rig:
        for f in sorted(Path(rig).iterdir()):
            if f.name == 'g3rig.json' or (f.suffix == '.png' and f.name.startswith('g3r-')):
                put(f)
    shutil.copy2(HERE/'golem'/'boss-golem.json', out/'boss-golem.json')   # the stone golem's stones: sent when one is first seen (Golems.dm), not with the rest
    js = ['// Built by art/gear3d/install.py from ' + ', '.join(SCRIPTS) + ': edit those, then run it again.']
    for s in SCRIPTS:
        js.append((HERE/s).read_text())
    (GAME/'Interface'/'gear3d.js').write_text('\n'.join(js) + '\n')
    pieces = sorted(json.load(open(HERE/'gear3d.json'))['pieces'])
    sheets = sorted(json.load(open(HERE/'anchors.json')))
    q = lambda xs: ', '.join(f'"{x}"=1' for x in xs)
    dm = ['// Generated by art/gear3d/install.py. Do not edit: run it again. Logic is in Gear3D.dm.', '',
          '// The pieces with a 3D look (gear3d.json), by the catalogue id\'s first two parts ("weapon.longsword").',
          f'var/list/rm_g3_pieces = list({q(p for p in pieces if p.startswith(("weapon.", "shield.", "helmet.")) and "@" not in p)})',
          '// The race sheets the pieces are anchored on (anchors.json).',
          f'var/list/rm_g3_sheets = list({q(sheets)})',
          '// What the page fetches (Interface/gear3d/), sent once to each player.',
          'var/list/rm_g3_files = list(' + ', '.join(f'"{f}"' for f in files) + ')', '']
    (GAME/'Code'/'Remastered'/'Gear3DData.dm').write_bytes('\n'.join(dm).encode('latin-1'))
    size = sum((out/f).stat().st_size for f in files)
    print(f'{len(files)} files, {size / 1e6:.1f} MB, in {out}; gear3d.js {len("".join(js)) / 1e3:.0f} KB')


if __name__ == '__main__':
    main(*sys.argv[1:])
